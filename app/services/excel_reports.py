"""Excel report generation service for multi-person fleet challan & payment review."""
from datetime import datetime, timezone
from io import BytesIO
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter


HEADER_FILL = PatternFill(start_color="0F172A", end_color="0F172A", fill_type="solid")
HEADER_FONT = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
SUBHEADER_FILL = PatternFill(start_color="E2E8F0", end_color="E2E8F0", fill_type="solid")
TITLE_FONT = Font(name="Calibri", size=14, bold=True, color="0F172A")
BOLD_FONT = Font(name="Calibri", size=10, bold=True, color="0F172A")
BODY_FONT = Font(name="Calibri", size=10, color="1E293B")
ALT_ROW_FILL = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")
UNPAID_FILL = PatternFill(start_color="FEE2E2", end_color="FEE2E2", fill_type="solid")
PAID_FILL = PatternFill(start_color="DCFCE7", end_color="DCFCE7", fill_type="solid")
THIN_BORDER = Border(
    left=Side(style="thin", color="CBD5E1"),
    right=Side(style="thin", color="CBD5E1"),
    top=Side(style="thin", color="CBD5E1"),
    bottom=Side(style="thin", color="CBD5E1"),
)
INR_FORMAT = "₹#,##0.00"


def _style_header_row(ws, row_idx: int, col_count: int) -> None:
    """Apply consistent navy header styling to a worksheet row."""
    ws.row_dimensions[row_idx].height = 24
    for col_idx in range(1, col_count + 1):
        cell = ws.cell(row=row_idx, column=col_idx)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = THIN_BORDER


def _auto_fit_columns(ws, max_width: int = 40) -> None:
    """Auto-adjust column widths based on cell values."""
    for col in ws.columns:
        col_letter = get_column_letter(col[0].column)
        longest = 0
        for cell in col:
            val = "" if cell.value is None else str(cell.value)
            if len(val) > longest:
                longest = len(val)
        ws.column_dimensions[col_letter].width = min(max(longest + 4, 12), max_width)


def generate_challan_checklist_workbook(
    challans: list,
    payments: list,
    generated_by: str,
    filters_summary: str = "All Fleet Challans",
) -> BytesIO:
    """Build a multi-sheet Excel workbook simplified for multi-person verification.

    Sheets:
    1. Summary - Executive totals and per-vehicle breakdown.
    2. Challan Checklist - Full challan rows with sign-off & remarks columns.
    3. Payment Settlements - Recorded payment references for cross-checking.
    """
    wb = Workbook()

    # --- Sheet 1: Summary ---
    ws_summary = wb.active
    ws_summary.title = "Summary"
    ws_summary["A1"] = "Balaji Transports - Fleet Challan & Payment Checklist"
    ws_summary["A1"].font = TITLE_FONT

    total_challans = len(challans)
    total_fine = sum(float(c.penalty_amount or 0) for c in challans)
    total_paid = sum(float(c.total_paid or 0) for c in challans)
    total_balance = sum(float(c.remaining_penalty or 0) for c in challans)
    unpaid_count = sum(1 for c in challans if c.payment_status in ("unpaid", "partially_paid"))

    meta_rows = [
        ("Generated By", generated_by),
        ("Generated At (UTC)", datetime.now(timezone.utc).strftime("%d-%b-%Y %H:%M")),
        ("Applied Filters", filters_summary),
        ("Total Challans", total_challans),
        ("Unpaid / Partial Challans", unpaid_count),
        ("Total Fine Amount", total_fine),
        ("Total Paid Amount", total_paid),
        ("Total Balance Due", total_balance),
    ]
    for idx, (label, value) in enumerate(meta_rows, start=3):
        c_label = ws_summary.cell(row=idx, column=1, value=label)
        c_label.font = BOLD_FONT
        c_label.fill = SUBHEADER_FILL
        c_label.border = THIN_BORDER
        c_val = ws_summary.cell(row=idx, column=2, value=value)
        c_val.font = BODY_FONT
        c_val.border = THIN_BORDER
        if "Amount" in label or "Balance" in label:
            c_val.number_format = INR_FORMAT

    # Per-vehicle breakdown on Summary sheet
    vehicle_stats = {}
    for c in challans:
        reg = c.vehicle.formatted_registration if c.vehicle else "Unknown"
        entry = vehicle_stats.setdefault(
            reg,
            {"type": c.vehicle.vehicle_type if c.vehicle else "-", "count": 0, "unpaid": 0, "fine": 0.0, "paid": 0.0, "due": 0.0},
        )
        entry["count"] += 1
        if c.payment_status in ("unpaid", "partially_paid"):
            entry["unpaid"] += 1
        entry["fine"] += float(c.penalty_amount or 0)
        entry["paid"] += float(c.total_paid or 0)
        entry["due"] += float(c.remaining_penalty or 0)

    breakdown_start = len(meta_rows) + 5
    ws_summary.cell(row=breakdown_start - 1, column=1, value="Vehicle-Wise Breakdown").font = TITLE_FONT
    v_headers = ["Vehicle No.", "Type", "Total Challans", "Unpaid Count", "Total Fine (₹)", "Paid (₹)", "Balance Due (₹)"]
    for col_idx, h in enumerate(v_headers, start=1):
        ws_summary.cell(row=breakdown_start, column=col_idx, value=h)
    _style_header_row(ws_summary, breakdown_start, len(v_headers))

    for offset, (reg, stats) in enumerate(sorted(vehicle_stats.items(), key=lambda x: x[1]["due"], reverse=True), start=1):
        r = breakdown_start + offset
        row_vals = [reg, stats["type"], stats["count"], stats["unpaid"], stats["fine"], stats["paid"], stats["due"]]
        for col_idx, val in enumerate(row_vals, start=1):
            cell = ws_summary.cell(row=r, column=col_idx, value=val)
            cell.font = BODY_FONT
            cell.border = THIN_BORDER
            if offset % 2 == 0:
                cell.fill = ALT_ROW_FILL
            if col_idx >= 5:
                cell.number_format = INR_FORMAT

    _auto_fit_columns(ws_summary)

    # --- Sheet 2: Challan Checklist ---
    ws_list = wb.create_sheet(title="Challan Checklist")
    headers = [
        "S.No",
        "Vehicle No.",
        "Vehicle Type",
        "Make & Model",
        "Challan No.",
        "Violation Type",
        "Location",
        "Violation Date",
        "Issuing Authority",
        "Fine Amount (₹)",
        "Paid Amount (₹)",
        "Balance Due (₹)",
        "Payment Status",
        "Driver Name",
        "Driver Mobile",
        "Trip Reference",
        "Deduction Status",
        "Checked By (Sign-off)",
        "Reviewer Remarks",
    ]
    for col_idx, h in enumerate(headers, start=1):
        ws_list.cell(row=1, column=col_idx, value=h)
    _style_header_row(ws_list, 1, len(headers))

    for idx, c in enumerate(challans, start=1):
        r = idx + 1
        fine = float(c.penalty_amount or 0)
        paid = float(c.total_paid or 0)
        due = float(c.remaining_penalty or 0)
        row_vals = [
            idx,
            c.vehicle.formatted_registration if c.vehicle else "-",
            c.vehicle.vehicle_type if c.vehicle else "-",
            c.vehicle.make_model if c.vehicle and c.vehicle.make_model else "-",
            c.challan_number or f"ID-{c.id}",
            c.violation_type,
            c.violation_location or "-",
            c.violation_date.strftime("%d-%b-%Y %H:%M") if c.violation_date else "-",
            c.issuing_authority or "-",
            fine,
            paid,
            due,
            (c.payment_status or "unpaid").replace("_", " ").title(),
            c.driver_name or "-",
            c.driver_mobile or "-",
            c.trip_reference or "-",
            (c.deduction_status or "pending").replace("_", " ").title(),
            "",
            "",
        ]
        for col_idx, val in enumerate(row_vals, start=1):
            cell = ws_list.cell(row=r, column=col_idx, value=val)
            cell.font = BODY_FONT
            cell.border = THIN_BORDER
            if col_idx in (10, 11, 12):
                cell.number_format = INR_FORMAT
            if col_idx == 13:
                cell.fill = PAID_FILL if c.payment_status == "paid" else UNPAID_FILL
            elif idx % 2 == 0:
                cell.fill = ALT_ROW_FILL

    ws_list.freeze_panes = "A2"
    ws_list.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{max(len(challans) + 1, 1)}"
    _auto_fit_columns(ws_list)

    # --- Sheet 3: Payment Settlements ---
    ws_pay = wb.create_sheet(title="Payment Settlements")
    p_headers = [
        "S.No",
        "Reference ID",
        "Payment Mode",
        "Challan No.",
        "Vehicle No.",
        "Payment Date",
        "Amount Paid (₹)",
        "Verification Status",
        "Recorded By",
        "Notes",
    ]
    for col_idx, h in enumerate(p_headers, start=1):
        ws_pay.cell(row=1, column=col_idx, value=h)
    _style_header_row(ws_pay, 1, len(p_headers))

    for idx, p in enumerate(payments, start=1):
        r = idx + 1
        row_vals = [
            idx,
            p.payment_reference,
            p.payment_mode or "-",
            p.challan.challan_number if p.challan and p.challan.challan_number else f"ID-{p.challan_id}",
            p.challan.vehicle.formatted_registration if p.challan and p.challan.vehicle else "-",
            p.payment_date.strftime("%d-%b-%Y") if p.payment_date else "-",
            float(p.amount_paid or 0),
            (p.verification_status or "").replace("_", " ").title(),
            p.recorded_by_user.full_name if p.recorded_by_user else "-",
            p.notes or "",
        ]
        for col_idx, val in enumerate(row_vals, start=1):
            cell = ws_pay.cell(row=r, column=col_idx, value=val)
            cell.font = BODY_FONT
            cell.border = THIN_BORDER
            if col_idx == 7:
                cell.number_format = INR_FORMAT
            if idx % 2 == 0:
                cell.fill = ALT_ROW_FILL

    ws_pay.freeze_panes = "A2"
    ws_pay.auto_filter.ref = f"A1:{get_column_letter(len(p_headers))}{max(len(payments) + 1, 1)}"
    _auto_fit_columns(ws_pay)

    output = BytesIO()
    wb.save(output)
    output.seek(0)
    return output


def generate_vehicle_compliance_workbook(vehicles: list, generated_by: str) -> BytesIO:
    """Build a Vehicle-Wise Compliance Excel workbook."""
    wb = Workbook()
    ws = wb.active
    ws.title = "Vehicle Compliance"

    headers = [
        "S.No",
        "Vehicle No.",
        "Vehicle Type",
        "Make & Model",
        "Registered Owner",
        "Department / Branch",
        "Assigned Manager",
        "Status",
        "Total Challans",
        "Unpaid Challans",
        "Total Outstanding (₹)",
        "Checked By (Sign-off)",
    ]
    for col_idx, h in enumerate(headers, start=1):
        ws.cell(row=1, column=col_idx, value=h)
    _style_header_row(ws, 1, len(headers))

    for idx, v in enumerate(vehicles, start=1):
        r = idx + 1
        all_challans = v.challans.all()
        unpaid_cnt = v.pending_challans_count
        outstanding = float(v.total_outstanding_penalty or 0)
        row_vals = [
            idx,
            v.formatted_registration,
            v.vehicle_type,
            v.make_model or "-",
            v.registered_owner or "-",
            v.department or "-",
            v.assigned_manager or "-",
            "Active" if v.is_active else "Inactive",
            len(all_challans),
            unpaid_cnt,
            outstanding,
            "",
        ]
        for col_idx, val in enumerate(row_vals, start=1):
            cell = ws.cell(row=r, column=col_idx, value=val)
            cell.font = BODY_FONT
            cell.border = THIN_BORDER
            if col_idx == 11:
                cell.number_format = INR_FORMAT
            if idx % 2 == 0:
                cell.fill = ALT_ROW_FILL

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{max(len(vehicles) + 1, 1)}"
    _auto_fit_columns(ws)

    output = BytesIO()
    wb.save(output)
    output.seek(0)
    return output
